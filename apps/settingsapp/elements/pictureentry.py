from ignis import widgets
from .entry import SettingEntry


class PictureEntry(SettingEntry):

    def __init__(self, image: str, width: int=200, height: int=200):
        self._image = widgets.Picture(
            image=image,
            width=width,
            height=height
        )
        
        super().__init__(
            widgets.Box(child=[
                self._image
            ])
        )
