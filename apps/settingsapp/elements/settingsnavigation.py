from ignis import widgets
import extra_widgets


class SettingsNavigation(widgets.Box):

    def __init__(self, icon_image: str="", onclick=None, pixel_size: int=40, *args, **kwargs):
        self._button = extra_widgets.IconButton(
            css_classes=["button"],
            icon=icon_image,
            on_click=onclick,
            pixel_size=pixel_size,
            *args,
            **kwargs
        )

        super().__init__(
            css_classes=["navigatorentry"],
            child=[self._button]
        )

    def activate(self):
        self.add_css_class('active')

    def deactivate(self):
        self.remove_css_class('active')
