from ignis import widgets
from .entry import SettingEntry


class SubHeaderEntry(SettingEntry):

    def __init__(self, subheader: str):
        self._subheader = widgets.Label(
            css_classes=["pagesubheader"],
            justify="left",
            wrap=True,
            wrap_mode='word',
            label=subheader
        )

        super().__init__(
            widgets.CenterBox(
                hexpand=True,
                vexpand=True,
                start_widget=widgets.Box(child=[self._subheader]),
                center_widget=widgets.Box(),
                end_widget=widgets.Box()
            )
        )
