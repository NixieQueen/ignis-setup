from typing import Callable

from extra_widgets import TextButton
from ignis import widgets
from .entry import SettingEntry


class ButtonEntry(SettingEntry):

    def __init__(self, text: str, on_click: function | Callable):
        self._button = TextButton(text=text, css_classes=['button'], on_click=on_click)
        
        super().__init__(
            widgets.Box(
                child=[self._button]
            )
        )
