from typing import Callable

from ignis import widgets
from .entry import SettingEntry


class InputboxEntry(SettingEntry):

    def __init__(self, text_context: str, on_accept: function | Callable, default_state: str=""):
        self._text_context = widgets.Label(
            css_classes=["pagetext"],
            justify="left",
            wrap=False,
            wrap_mode='word',
            label=text_context
        )
        self._inputbox = widgets.Entry(
            css_classes = ["inputbox"],
            placeholder_text="...",
            on_accept=on_accept,
            on_change=on_accept
        )
        if default_state:
            self._inputbox.set_text(default_state)

        super().__init__(
            widgets.CenterBox(
                hexpand=True,
                vexpand=True,
                start_widget=widgets.Box(child=[self._text_context]),
                center_widget=widgets.Box(),
                end_widget=widgets.Box(child=[self._inputbox])
            )
        )
