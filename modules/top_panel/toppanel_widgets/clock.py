from ignis import widgets as Widget
from ignis import utils as Utils
import datetime

import extra_widgets


class Clocklabel(Widget.Label):

    def __init__(self):
        super().__init__(
            label=Utils.Poll(
                1_000, lambda _: datetime.datetime.now().strftime("%H:%M:%S")
            ).bind("output")
        )


class Clock(extra_widgets.Button):

    def __init__(self):
        # poll for current time every second
        super().__init__(
            css_classes=["toppanel", "clock"],
            child=Clocklabel(),
        )
