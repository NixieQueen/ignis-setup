from typing import Callable, TypeVar

_serviceinstance = TypeVar("_serviceinstance", bound="BaseService")

class BaseService:

    _instance: _serviceinstance | None = None

    def __init__(self, signals: list[str]=[]):
        self._signals = dict()
        for signal in signals:
            self._signals[signal] = []

    def emit(self, signal, *args) -> None:
        if not (signal in self._signals):
            return

        if not args:
            for function in self._signals[signal]:
                function()
        else:
            for function in self._signals[signal]:
                function(*args)

    def bind(self, signal, function: Callable):
        if not (signal in self._signals):
            return

        self._signals[signal].append(function)

    @classmethod
    def get_default(cls: type[_serviceinstance], *args) -> _serviceinstance:
        if cls._instance is None:
            if args:
                cls._instance = cls(*args)
            else:
                cls._instance = cls()
        return cls._instance

    
